const languageChangeListeners = new Set<() => void>();

export function onLanguageChange(listener: () => void): () => void {
  languageChangeListeners.add(listener);
  return () => {
    languageChangeListeners.delete(listener);
  };
}

export function getCurrentLanguageCode(): SupportLanguage {
  return currentLanguageCode;
}

export function setLanguage(code: SupportLanguage | "en" | "vi"): void {
  const enumCode =
    code === SupportLanguage.Vi ? SupportLanguage.Vi : SupportLanguage.En;
  const raw = dictionaries[enumCode];
  currentTranslations = LangSchema.parse(raw);
  currentLanguageCode = enumCode;
  languageChangeListeners.forEach((listener) => listener());
}

export function initI18n(language?: SupportLanguage | "en" | "vi"): void {
  if (language) {
    setLanguage(language);
  }
}

// Initialize default language matching SettingsSchema (En) so translations are ready on module load
setLanguage(SupportLanguage.En);

function isLangKey(key: string, dict: Partial<Lang>): key is keyof Lang {
  return Object.hasOwn(dict, key);
}

/**
 * HTML-encode interpolation params before substitution.
 * Locale templates may contain trusted static markup (<strong>, <br/>) rendered via
 * SafeHtml/DOMParser; interpolated values are UNTRUSTED data (site-controlled rp names,
 * usernames, domains...) and MUST be escaped so they can never inject markup or
 * event-handler attributes into extension pages.
 */
export function escapeHtmlParam(value: unknown): string {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

export function t(
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const current = currentTranslations;
  let msg = current[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      // Security: escape interpolated values (see escapeHtmlParam).
      msg = msg.replaceAll(`{${k}}`, escapeHtmlParam(v));
    });
  }
  if (msg.includes("{")) {
    msg = msg.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, subKey) => {
      if (isLangKey(subKey, current)) {
        const subMsg = current[subKey];
        if (typeof subMsg === "string") {
          return subMsg;
        }
      }
      return match;
    });
  }
  return msg;
}

/**
 * Định dạng ngày giờ tự động dựa trên ngôn ngữ/khu vực hoạt động hiện tại.
 */
export function formatDateTime(dateInput: Date | number | string): string {
  const d = new Date(dateInput);
  if (Number.isNaN(d.getTime())) return "";

  const locale = currentLanguageCode === SupportLanguage.Vi ? "vi-VN" : "en-US";
  return d.toLocaleString(locale, {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  });
}
